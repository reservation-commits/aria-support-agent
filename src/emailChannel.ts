/**
 * emailChannel.ts — segunda "casca" da Aria: atendimento por EMAIL.
 *
 * Reaproveita todo o motor (runAgent, tools, sessões, fila, handoff, dedup);
 * este módulo só faz a ponte com a caixa Gmail (support@theworldkeys.com):
 *
 *   • POLLING via Gmail API (users.messages.list, q="in:inbox is:unread") a
 *     cada EMAIL_POLL_SECONDS — email tolera latência; polling é mais simples
 *     e robusto que push/Pub-Sub.
 *   • Cada email vira um turno: texto novo (histórico citado removido) +
 *     anexos de imagem/PDF como blocos multimodais.
 *   • Resposta enviada pela própria Gmail API na MESMA thread (In-Reply-To/
 *     References + threadId) — DKIM/SPF corretos e cópia em Enviados para o
 *     time acompanhar.
 *   • Guardas anti-loop: nunca responde auto-replies (Auto-Submitted,
 *     Precedence: bulk/list), remetentes no-reply/daemon, nem a própria caixa.
 *   • Identidade confiável = endereço do remetente (ver identity.ts); a chave
 *     de conversa é "email:<addr>" em toda a stack (fila, sessões, dashboard).
 *
 * DESLIGADO por padrão — liga com EMAIL_ENABLED=true + credenciais OAuth
 * (GMAIL_CLIENT_ID/SECRET/REFRESH_TOKEN com escopo gmail.modify).
 */

